#!/usr/bin/env python3
"""Write the vm/ scripts of a qemu lab.

astrona pipes each bootstrap, testing and validation script of a qemu lab
alone into the lab VM (`ssh ... bash -s`) and copies no other file. The lab
keeps the same files as a kind lab (setup.sh, apply.sh, validate.sh,
check.py, live.py, ...), and this script generates its vm/ folder:

- vm/install.sh builds the one-node kubeadm cluster, writes the lab files to
  /opt/astrona-lab inside the VM and runs bootstrap/setup.sh from there.
- vm/verify-start.sh, vm/apply-solution.sh, vm/wait-solved.sh and one
  vm/validate-<outcome>.sh per outcome run the copy in /opt/astrona-lab.

    python3 scripts/ci/vm-lab.py sections/section-020/module-30/labs/lab-02
    python3 scripts/ci/vm-lab.py --check <lab directory>...

--check writes nothing and fails when a vm/ file is missing or stale.
"""
from pathlib import Path
import sys

import yaml

VM_DIRECTORY = '/opt/astrona-lab'
DELIMITER = 'ASTRONA_LAB_FILE'
# Course pages and astrona's own files stay on the host.
HOST_ONLY = {'config.yaml', 'question.md', 'solution.md', 'README.md'}
HEADER = (
    '#!/usr/bin/env bash\n'
    '# Generated by scripts/ci/vm-lab.py from the lab files. Do not edit; change\n'
    '# the lab files and run: python3 scripts/ci/vm-lab.py <lab directory>\n'
)
WRAPPERS = {
    'vm/verify-start.sh': 'testing/verify-start.sh',
    'vm/apply-solution.sh': 'solution/apply.sh',
    'vm/wait-solved.sh': 'testing/wait-solved.sh',
}


def lab_files(directory):
    """The files copied into the VM, as paths relative to the lab."""
    for path in sorted(directory.rglob('*')):
        relative = path.relative_to(directory)
        if path.is_file() and relative.parts[0] not in ('vm', 'docs') and str(relative) not in HOST_ONLY:
            yield relative


def install_script(directory, name):
    lines = [
        HEADER,
        '# astrona pipes this file alone into the lab VM, where it runs as the VM\n'
        '# administrator user. It builds the one-node kubeadm cluster, writes the lab\n'
        f'# files to {VM_DIRECTORY} and runs bootstrap/setup.sh from there.\n'
        'set -euo pipefail\n'
        f'cluster="astro-{name}"\n'
        '# The learner logs in as student, so student gets the admin kubeconfig too.\n'
        'kube_users=(--user "$(id -un)")\n'
        'getent passwd student >/dev/null && kube_users+=(--user student)\n'
        'sudo /usr/local/sbin/astrona-kubeadm-init --cluster-name "$cluster" "${kube_users[@]}"\n'
        f'lab="{VM_DIRECTORY}"\n'
        'sudo rm -rf "$lab"\n'
        'write_file() {\n'
        '  sudo mkdir -p "$(dirname "$lab/$2")"\n'
        '  sudo tee "$lab/$2" >/dev/null\n'
        '  sudo chmod "$1" "$lab/$2"\n'
        '}\n',
    ]
    for relative in lab_files(directory):
        path = directory / relative
        text = path.read_text()
        if DELIMITER in text:
            raise ValueError(f'{path}: contains {DELIMITER}')
        if not text.endswith('\n'):
            text += '\n'
        mode = '0755' if path.stat().st_mode & 0o111 else '0644'
        lines.append(f"write_file {mode} {relative} <<'{DELIMITER}'\n{text}{DELIMITER}\n")
    lines.append('bash "$lab/bootstrap/setup.sh"\n')
    return ''.join(lines)


def wrapper(target):
    return (
        HEADER
        + '# astrona pipes this file alone into the lab VM. It runs the copy of\n'
        + f'# {target} that vm/install.sh wrote to {VM_DIRECTORY}.\n'
        + f'exec bash {VM_DIRECTORY}/{target}\n'
    )


def generate(directory):
    """Map each vm/ path of the lab to its text."""
    cfg = yaml.safe_load((directory / 'config.yaml').read_text())
    files = {'vm/install.sh': install_script(directory, cfg['metadata']['name'])}
    for path, target in WRAPPERS.items():
        files[path] = wrapper(target)
    for grader in cfg['validation']['scripts']:
        files[f'vm/validate-{grader["name"]}.sh'] = wrapper(f'validation/validate-{grader["name"]}.sh')
    return files


def stale(directory):
    """vm/ paths that are missing, out of date or no longer generated."""
    expected = generate(directory)
    present = {str(path.relative_to(directory)) for path in directory.glob('vm/*')}
    wrong = {path for path, text in expected.items() if not (directory / path).exists() or (directory / path).read_text() != text}
    return sorted(wrong | (present - set(expected)))


def main(arguments):
    check = '--check' in arguments
    directories = [Path(item) for item in arguments if item != '--check']
    if not directories:
        sys.exit(__doc__)
    failed = False
    for directory in directories:
        if check:
            for path in stale(directory):
                print(f'{directory}: {path} is stale; run python3 scripts/ci/vm-lab.py {directory}')
                failed = True
            continue
        for old in directory.glob('vm/*'):
            old.unlink()
        for path, text in generate(directory).items():
            target = directory / path
            target.parent.mkdir(exist_ok=True)
            target.write_text(text)
            target.chmod(0o755)
        print(f'wrote {directory}/vm')
    sys.exit(1 if failed else 0)


if __name__ == '__main__':
    main(sys.argv[1:])
